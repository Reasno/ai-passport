#!/usr/bin/env python3
"""Generate the Pocket Garden pixel-art tables from the native PNG artwork.

Plant sprites (48x48) and their overlays (16x16) are stored as palette run-length
data and decoded on the device into one small RGB565A8 buffer. Menu icons and the
watering frames are stored ready to draw as RGB565A8.
    tools/generate_garden_assets.py [art_dir]
"""
import pathlib
import struct
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "main" / "assets"
CROPS = ["radish", "lettuce", "basil", "bean", "tomato", "rosemary"]
STAGES = ["seed", "seedling", "growing", "mature"]
VARIANTS = ["", "-dry", "-deficient"]
OVERLAYS = ["weed", "pest", "moon"]
ICONS = ["water", "fertilizer", "weed_bottle", "pest_bottle", "ready"]
WATERING_FRAMES = 4
MAX_RUN = 8


def load(path):
    image = Image.open(path).convert("RGBA")
    pixels = [image.getpixel((x, y)) for y in range(image.height) for x in range(image.width)]
    for p in pixels:
        if p[3] not in (0, 255):
            raise SystemExit(f"{path.name}: alpha must be 0 or 255")
    return image.width, image.height, pixels


def rgb565(p):
    return ((p[0] >> 3) << 11) | ((p[1] >> 2) << 5) | (p[2] >> 3)


def rle(pixels, palette):
    out = bytearray()
    i = 0
    while i < len(pixels):
        key = pixels[i][:3] if pixels[i][3] else None
        run = 1
        while i + run < len(pixels) and run < MAX_RUN:
            nxt = pixels[i + run]
            if (nxt[:3] if nxt[3] else None) != key:
                break
            run += 1
        index = 0 if key is None else palette[key]
        out.append(((run - 1) << 5) | index)
        i += run
    return out


def c_bytes(data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "    " + ",\n    ".join(rows)


def main():
    art = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "garden-art"
    sprites = {}
    for crop in CROPS:
        for stage in STAGES:
            for variant in VARIANTS:
                path = art / f"{crop}-{stage}{variant}.png"
                if path.is_file():
                    w, h, px = load(path)
                    if (w, h) != (48, 48):
                        raise SystemExit(f"{path.name}: expected 48x48")
                    sprites[(crop, stage, variant)] = px
    overlays = {}
    for name in OVERLAYS:
        w, h, px = load(art / f"icon-{name}.png")
        if (w, h) != (16, 16):
            raise SystemExit(f"icon-{name}.png: expected 16x16")
        overlays[name] = px
    colors = sorted({p[:3] for px in list(sprites.values()) + list(overlays.values()) for p in px if p[3]})
    if len(colors) > 31:
        raise SystemExit(f"palette has {len(colors)} colors; RLE index allows 31")
    palette = {c: i + 1 for i, c in enumerate(colors)}

    lines = [
        "/* Generated by tools/generate_garden_assets.py; do not edit. */",
        '#include "garden_assets.h"',
        "",
        f"const uint16_t garden_palette[{len(colors) + 1}] = {{0x0000, "
        + ", ".join(f"0x{rgb565(c + (255,)):04X}" for c in colors) + "};",
        "",
    ]
    blobs = []
    for (crop, stage, variant), px in sprites.items():
        name = f"s_{crop}_{stage}{variant.replace('-', '_')}"
        data = rle(px, palette)
        blobs.append(len(data))
        lines += [f"static const uint8_t {name}[] = {{", c_bytes(data), "};"]
    for name, px in overlays.items():
        data = rle(px, palette)
        lines += [f"static const uint8_t s_overlay_{name}[] = {{", c_bytes(data), "};"]
    lines += ["", "const garden_rle_t garden_sprites[GARDEN_ART_CROPS][GARDEN_ART_STAGES][GARDEN_ART_VARIANTS] = {"]
    for crop in CROPS:
        lines.append("    {")
        for stage in STAGES:
            refs = []
            for variant in VARIANTS:
                key = (crop, stage, variant) if (crop, stage, variant) in sprites else (crop, stage, "")
                if key not in sprites:
                    raise SystemExit(f"missing healthy sprite {crop}-{stage}")
                name = f"s_{key[0]}_{key[1]}{key[2].replace('-', '_')}"
                refs.append(f"{{{name}, sizeof({name})}}")
            lines.append("        {" + ", ".join(refs) + "},")
        lines.append("    },")
    lines += ["};", "", "const garden_rle_t garden_overlays[GARDEN_ART_OVERLAYS] = {"]
    lines += [f"    {{s_overlay_{n}, sizeof(s_overlay_{n})}}," for n in OVERLAYS]
    lines += ["};", ""]

    icon_names = [f"icon-{n}.png" for n in ICONS] + [f"watering-frame-{i}.png" for i in range(WATERING_FRAMES)]
    for file_name in icon_names:
        w, h, px = load(art / file_name)
        if (w, h) != (16, 16):
            raise SystemExit(f"{file_name}: expected 16x16")
        data = bytearray()
        for p in px:
            data += struct.pack("<H", rgb565(p) if p[3] else 0)
        data += bytes(p[3] for p in px)
        name = "s_icon_" + file_name[:-4].replace("icon-", "").replace("-", "_")
        lines += [f"static const uint8_t {name}_data[] = {{", c_bytes(data), "};"]
    lines += ["", "const lv_image_dsc_t garden_icons[GARDEN_ICON_COUNT] = {"]
    for file_name in icon_names:
        name = "s_icon_" + file_name[:-4].replace("icon-", "").replace("-", "_")
        lines.append(
            "    {.header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, "
            f".w = 16, .h = 16, .stride = 32}}, .data_size = sizeof({name}_data), .data = {name}_data}},"
        )
    lines += ["};", ""]
    (OUT / "garden_assets.c").write_text("\n".join(lines), encoding="utf-8")
    print(f"palette={len(colors)} sprites={len(sprites)} rle_bytes={sum(blobs)} icons={len(icon_names)}")


if __name__ == "__main__":
    main()
