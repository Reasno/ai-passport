#!/usr/bin/env python3
"""Generate exact-size monochrome UI icon masks for LVGLImage.py conversion."""
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "main" / "assets" / "icons"
MASKS = {
"task":[0x1F8,0x108,0x1F8,0x100,0x17C,0x144,0x17C,0x100,0x1F8,0,0x0A0,0x040],
"gift":[0x040,0x0E0,0x1F0,0x3F8,0x7FC,0x404,0x7FC,0x444,0x444,0x444,0x7FC,0],
"game":[0,0x0C0,0x1E0,0x3F0,0x318,0x7FC,0x54C,0x7FC,0x198,0x330,0x660,0],
"radar":[0x040,0x0E0,0x040,0x151,0x040,0x0E0,0x155,0x040,0x0E0,0x1F1,0,0],
"rps":[0x1B0,0x3F8,0x268,0x3F8,0x1B0,0x040,0x2A8,0x1F0,0x3F8,0x150,0x208,0],
"tv":[0x7F0,0x410,0x5D0,0x550,0x5D0,0x410,0x7F0,0x100,0x3F8,0x208,0x3F8,0],
"ticket":[0x060,0x3F8,0x7FC,0x404,0x55C,0x554,0x55C,0x404,0x7FC,0x3F8,0x060,0],
"check":[0,0x004,0x00C,0x418,0x630,0x360,0x1C0,0x080,0,0,0,0],
"lock":[0x0E0,0x110,0x110,0x3F8,0x208,0x2A8,0x208,0x3F8,0,0,0,0],
"wifi":[0,0,0x3F8,0x404,0x1F0,0x208,0x0E0,0x110,0x040,0,0x040,0],
"battery":[0,0x3F0,0x408,0x7EC,0x7EC,0x7EC,0x7EC,0x408,0x3F0,0,0,0],
}
SCALES = {"task":[2],"gift":[2,3],"game":[2],"radar":[3,5],"rps":[3,6],"tv":[3],"ticket":[3],"check":[2,3],"lock":[3],"wifi":[1],"battery":[1]}
OUT.mkdir(parents=True, exist_ok=True)
for old in OUT.glob("generic_icon_*.*"):
    old.unlink()
for name, rows in MASKS.items():
    base = Image.new("RGBA", (12,12), (255,255,255,0))
    base.putdata([(255,255,255,255) if rows[y] & (0x800 >> x) else (255,255,255,0) for y in range(12) for x in range(12)])
    for scale in SCALES[name]:
        image = base.resize((12*scale,12*scale), Image.Resampling.NEAREST)
        image.save(OUT / f"generic_icon_{name}_s{scale}.png")
print("generated exact-size icon masks")
